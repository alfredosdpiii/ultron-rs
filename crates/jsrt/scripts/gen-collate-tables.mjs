// Generates the collation tables of jsrt's `locale_compare` from the running Node's ICU (`localeCompare` with no
// locale, the TypeScript product's default). Run: `node scripts/gen-collate-tables.mjs > src/collate/tables.rs` (from crates/jsrt).
// Covers: JS whitespace, ASCII + Latin-1 + General Punctuation + currency symbols, combining marks U+0300-U+036F,
// and the letters of Latin-1 Supplement and Latin Extended-A (U+00C0-U+017F).
const cmp = (a, b) => Math.sign(a.localeCompare(b));
const base = new Intl.Collator("und", { sensitivity: "base" });
const accent = new Intl.Collator("und", { sensitivity: "accent" });
const hex = (c) => `'\\u{${c.codePointAt(0).toString(16)}}'`;
const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i));
const out = [];
out.push(`// Generated by gen-collate-tables.mjs from Node ${process.versions.node} (ICU ${process.versions.icu}); do not edit.`);

// Whitespace and punctuation/symbols: one primary rank per run of characters that compare equal at base strength;
// within a run, a tertiary rank in sort order.
const space = ["\t", "\n", "\v", "\f", "\r", "\u0085", "\u2028", "\u2029", " ", "\u00a0", "\u1680",
  ...range(0x2000, 0x200a), "\u202f", "\u205f", "\u3000"];
const latin1Symbols = range(0xa1, 0xbf).filter((c) => !/[\p{L}\p{N}\u00ad]/u.test(c)).concat(["\u00d7", "\u00f7"]);
const general = range(0x2010, 0x2027).concat(range(0x2030, 0x205e)).filter((c) => /[\p{P}\p{S}]/u.test(c));
// A currency sign that decomposes to letters (U+20A8 RUPEE SIGN is `Rs`) sorts as those letters.
const currency = range(0x20a0, 0x20c0).filter((c) => /\p{Sc}/u.test(c) && !/\p{L}/u.test(c.normalize("NFKD")) && c !== "\u20a7");
// U+20A7 PESETA SIGN has no decomposition but collates as `pts`.
const spelled = { "\u20a7": "pts" };
const letterSymbols = range(0x20a0, 0x20c0).filter((c) => /\p{L}/u.test(c.normalize("NFKD")) || spelled[c]);
const ascii = range(0x21, 0x7e).filter((c) => !/[0-9A-Za-z]/.test(c));
const symbols = [...new Set([...space, ...ascii, ...latin1Symbols, ...general, ...currency])].sort(cmp);
// A symbol equal at base strength to its compatibility decomposition (`\u2026` is `...`) expands to that one's ranks.
const expands = (c) => {
  const k = c.normalize("NFKD");
  return [...k].length > 1 && [...k].every((x) => symbols.includes(x)) && base.compare(c, k) === 0 ? [...k] : null;
};
let rank = 0;
let tertiary = 0;
const ranks = new Map();
const singles = symbols.filter((c) => !expands(c));
singles.forEach((c, i) => {
  if (i > 0 && base.compare(singles[i - 1], c) !== 0) {
    rank += 1;
    tertiary = 0;
  } else if (i > 0 && cmp(singles[i - 1], c) !== 0) {
    tertiary += 1;
  }
  ranks.set(c, [rank, tertiary]);
});
const rows = symbols.map((c) => {
  const parts = expands(c);
  const currency = singles.indexOf(c) >= singles.findIndex((x) => /\p{Sc}/u.test(x));
  if (parts) return `(${hex(c)}, &[${parts.map((x) => ranks.get(x)[0]).join(", ")}], 3, false)`;
  return `(${hex(c)}, &[${ranks.get(c)[0]}], ${ranks.get(c)[1]}, ${currency})`;
});
out.push("/// `(char, primary ranks, tertiary, currency)`, sorted by char; whitespace and punctuation sort before digits,");
out.push("/// currency after the symbols this table does not list. `\u2026` expands to the ranks of `...`.");
const byChar = (rowsWithChar) => rowsWithChar.sort((a, b) => a[0].codePointAt(0) - b[0].codePointAt(0));
const symRows = byChar(symbols.map((c, i) => [c, rows[i]])).map((r) => r[1]);
out.push(`pub(crate) const SYMBOLS: &[(char, &[u16], u8, bool)] = &[\n    ${symRows.join(",\n    ")},\n];`);

// Combining marks: secondary ranks, from `o` + mark at accent strength.
const marks = range(0x300, 0x362).filter((m) => m !== "\u034f").sort((a, b) => accent.compare("o" + a, "o" + b));
const markRank = new Map();
let r = 0;
marks.forEach((m, i) => {
  if (i > 0 && accent.compare("o" + marks[i - 1], "o" + m) !== 0) r += 1;
  markRank.set(m, 2 * (r + 1));
});
out.push("/// `(combining mark, secondary weight)`, sorted by char; even weights, so a letter's own accent can sit between.");
out.push(`pub(crate) const MARKS: &[(char, u16)] = &[\n    ${byChar([...markRank]).map(([m, w]) => `(${hex(m)}, ${w})`).join(",\n    ")},\n];`);

// Letters: \u00aa, \u00ba, the combining Latin letters U+0363-U+036F, and U+00C0-U+017F.
const letters = ["\u00aa", "\u00ba", ...range(0x363, 0x36f), ...range(0xc0, 0x17f).filter((c) => /\p{L}/u.test(c)), ...letterSymbols];
const alphabet = range(0x61, 0x7a);
const pairs = alphabet.flatMap((a) => alphabet.map((b) => a + b));
// Letters with no ASCII base: their own primary, placed after the ASCII letter they follow.
const own = letters.filter((c) => !spelled[c] && !alphabet.concat(pairs).some((x) => base.compare(c, x) === 0) && !/^[a-z]/i.test(c.normalize("NFD")));
const ownLower = [...new Set(own.map((c) => c.toLowerCase()).filter((c) => [...c].length === 1))];
const order = [...alphabet, ...ownLower].sort(cmp);
const primaryOf = new Map();
let letterIndex = -1;
let sub = 0;
for (const c of order) {
  if (alphabet.includes(c)) {
    letterIndex = alphabet.indexOf(c);
    sub = 0;
  } else {
    sub += 1;
  }
  primaryOf.set(c, (letterIndex + 1) * 16 + sub);
}
const letterRows = [];
for (const c of letters) {
  const upper = c !== c.toLowerCase() || c === "\u0130";
  const nfd = c.normalize("NFD");
  let prims;
  let sec = 0;
  let ter = upper ? 2 : 0;
  if (/^[a-z][\u0300-\u036f]$/i.test(nfd)) {
    prims = [primaryOf.get(nfd[0].toLowerCase())];
    sec = markRank.get(nfd[1]);
  } else if (own.includes(c) || ownLower.includes(c.toLowerCase())) {
    const key = c.toLowerCase();
    if (!primaryOf.has(key)) continue;
    prims = [primaryOf.get(key)];
  } else {
    const k = spelled[c] ?? c.normalize("NFKD").toLowerCase();
    const b = alphabet.concat(pairs).find((x) => base.compare(c, x) === 0) ?? (/^[a-z]+$/.test(k) && base.compare(c, k) === 0 ? k : null);
    if (!b) continue;
    prims = [...b].map((x) => primaryOf.get(x));
    if (b.length === 1 && accent.compare(c, b) === 0) {
      // Equal to its base but for case: a variant (\u00aa, \u0363, \u017f), placed among the base's case forms.
      ter = cmp(c, b.toUpperCase()) < 0 ? 1 : upper ? 4 : 3;
    } else if (b.length === 1) {
      // A letter equal to its base at base strength but not decomposable (\u00f8, \u0142, \u0111, \u0127, \u0140): an odd secondary between
      // the marks that sort around it.
      const below = marks.filter((m) => accent.compare(b + m, c) < 0);
      const equal = marks.find((m) => accent.compare(b + m, c) === 0);
      sec = equal ? markRank.get(equal) : (below.length ? markRank.get(below[below.length - 1]) : 0) + 1;
    } else {
      ter = upper ? 4 : 3; // \u00e6, \u00df, \u0133, \u0153: after every case variant of the expansion.
      // \u00e6, \u00df and \u0153 also differ at the secondary level, above every accent.
      if (accent.compare(c, b) !== 0) sec = 2 * (Math.max(...markRank.values()) / 2) + 1;
    }
  }
  letterRows.push([c, `(${hex(c)}, [${prims[0]}, ${prims[1] ?? 0}, ${prims[2] ?? 0}], ${sec}, ${ter})`]);
}
out.push("/// `(letter, primaries (0: none), secondary, tertiary)`, sorted by char. Tertiary: 0 lowercase, 1 a small variant,");
out.push("/// 2 uppercase, 3 and 4 a compatibility form (lower, upper). An ASCII letter `x` has primary");
out.push("/// `(x - 'a' + 1) * 16`; a letter of its own sorts after the ASCII letter it follows.");
out.push(`pub(crate) const LETTERS: &[(char, [u16; 3], u16, u8)] = &[\n    ${byChar(letterRows).map((r) => r[1]).join(",\n    ")},\n];`);
console.log(out.join("\n"));
