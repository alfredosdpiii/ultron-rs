//! The host requests runtime.py's clients (`packages/coding-agent/src/ultron/rlm/*.py`) send, one row per op: the
//! module that serves it, the payload keys it takes and the reply keys the clients read. `tests/ops.rs` checks the
//! Python clients against this table (every op they send is a row, every row is sent, no key outside its row),
//! and handlers refuse other payload keys with [`fields`].

use serde_json::{Map, Value};

pub struct Op {
    pub name: &'static str,
    /// The module (or modules, comma-separated) whose handler serves the op.
    pub owner: &'static str,
    pub payload: &'static [&'static str],
    pub reply: &'static [&'static str],
}

const fn op(
    name: &'static str,
    owner: &'static str,
    payload: &'static [&'static str],
    reply: &'static [&'static str],
) -> Op {
    Op {
        name,
        owner,
        payload,
        reply,
    }
}

