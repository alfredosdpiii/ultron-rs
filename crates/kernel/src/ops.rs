/// The TS host's refusal of a request kind it does not serve, which the model sees.
pub fn not_wired(kind: &str) -> String {
    format!("Ultron RLM host request is not wired: {kind}")
}

pub fn find(name: &str) -> Option<&'static Op> {
    OPS.iter().find(|op| op.name == name)
}

/// Refuses a payload key that op `name` does not take: "Unknown payload field: <key>".
///
/// # Panics
/// When `name` is no row of [`OPS`].
pub fn fields(name: &str, payload: &Map<String, Value>) -> Result<(), String> {
    let op = find(name).unwrap_or_else(|| panic!("{name} is not in kernel::ops::OPS"));
    jsrt::payload::fields(payload, op.payload)
}
